// Generates src/styles/tokens.css and src/styles/tokens.ts from design/tokens.json (the League Remote design system).
//   node scripts/gen-tokens.mjs        (also run by `npm run tokens` and `npm run build`)
//
// - Colour and shadow tokens: `light` on :root, `dark` under prefers-color-scheme: dark, `light-hc` / `dark-hc` under
//   prefers-contrast: more (combined with the scheme query). `{name}` references become var(--name).
// - Dynamic Type (`html { font: -apple-system-body }`: the root font is the user's body size, 17px by default).
//   Like iOS, text grows the most and layout the least:
//   · type styles grow with the text size up to their AX5 size (`maxFontSize`), so big styles grow less than body;
//   · spacing grows up to dynamicType.spacingMaxScale × and sizes up to dynamicType.sizeMaxScale ×;
//   · tokens marked `"dynamic": false` (bar chrome: the tab bar) stay fixed, as iOS bars do.
//   Radii, z-index, durations and easings stay as authored.
// - One class per type style (.large-title, .body, …) with SF Pro tracking.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const tokens = JSON.parse(readFileSync(resolve(root, 'design/tokens.json'), 'utf8'))
const OUT = resolve(root, 'src/styles/tokens.css')
const BASE_PX = 17
const { spacingMaxScale, sizeMaxScale } = tokens.dynamicType

const px = (value) => Number(String(value).replace(/px$/, ''))
const ms = (value) => Number(String(value).replace(/ms$/, ''))
const round = (n) => +n.toFixed(4)
/** px at the default text size → rem (grows with the text size). */
const rem = (n) => (n === 0 ? '0' : `${round(n / BASE_PX)}rem`)
/** Grows with the text size, but never past `max` px. */
const capped = (n, max) => (n === 0 ? '0' : `min(${rem(n)}, ${round(max)}px)`)
const dynamic = (t, maxScale) => (t.dynamic === false ? t.value : capped(px(t.value), px(t.value) * maxScale))

const ref = (value) => String(value).replace(/\{([a-z0-9-]+)\}/g, 'var(--$1)')
const decl = (name, value) => `  --${name}: ${value};`

const THEMES = ['light', 'dark', 'light-hc', 'dark-hc']
const themed = Object.fromEntries(THEMES.map((t) => [t, []]))
for (const group of [tokens.color.tokens, tokens.shadow.tokens]) {
  for (const t of group) for (const theme of THEMES) themed[theme].push(decl(t.name, ref(t.value[theme])))
}

const constants = []
for (const [key, family] of Object.entries(tokens.type.families)) constants.push(decl(`font-${key}`, family))
for (const t of tokens.spacing.tokens) constants.push(decl(t.name, dynamic(t, spacingMaxScale)))
for (const t of tokens.size.tokens) constants.push(decl(t.name, dynamic(t, sizeMaxScale)))
for (const t of tokens.radius.tokens) constants.push(decl(t.name, t.value))
for (const t of tokens.zIndex.tokens) constants.push(decl(t.name, t.value))
for (const t of tokens.duration.tokens) constants.push(decl(t.name, t.value))
for (const t of tokens.easing.tokens) constants.push(decl(t.name, t.value))

const NUMERALS = new Set(['clock-hero', 'clock-card', 'countdown', 'timer', 'code-digit'])
const typeClasses = []
for (const group of tokens.type.groups) {
  for (const s of group.styles) {
    const family = s.family ?? group.family
    const size = px(s.fontSize)
    const line = px(s.lineHeight)
    const max = s.maxFontSize ? px(s.maxFontSize) : null
    const fontSize = s.dynamic === false ? s.fontSize : max ? capped(size, max) : rem(size)
    const lineHeight = s.dynamic === false ? s.lineHeight : max ? capped(line, (line / size) * max) : rem(line)
    // The size alone as a property too: fields need it with a 16px floor (iOS zooms into smaller inputs).
    constants.push(decl(`font-size-${s.name}`, fontSize))
    typeClasses.push(
      `.${s.name} {
  font-family: var(--font-${family});
  font-size: var(--font-size-${s.name});
  line-height: ${lineHeight};
  font-weight: ${s.fontWeight};
  letter-spacing: calc(${s.letterSpacing} * var(--lr-tracking));${NUMERALS.has(s.name) ? '\n  font-variant-numeric: tabular-nums;' : ''}
}`,
    )
  }
}

const block = (selector, lines) => `${selector} {\n${lines.join('\n')}\n}`
const css = `/* Generated by scripts/gen-tokens.mjs from design/tokens.json — do not edit by hand. */

${block(':root', ['  color-scheme: light dark;', ...themed.light, ...constants, '  /* SF Pro tracking per type style; set to 0 to drop it (see README). */', '  --lr-tracking: 1;'])}

@media (prefers-color-scheme: dark) {
${block('  :root', themed.dark.map((l) => `  ${l}`)).replace(/\n}$/, '\n  }')}
}

@media (prefers-contrast: more) {
${block('  :root', themed['light-hc'].map((l) => `  ${l}`)).replace(/\n}$/, '\n  }')}
}

@media (prefers-contrast: more) and (prefers-color-scheme: dark) {
${block('  :root', themed['dark-hc'].map((l) => `  ${l}`)).replace(/\n}$/, '\n  }')}
}

/* Dynamic Type: WebKit maps -apple-system-body to the user's text size (17px at the default size). */
html {
  font-size: ${BASE_PX}px;
}
@supports (font: -apple-system-body) {
  html {
    font: -apple-system-body;
  }
}

${typeClasses.join('\n')}
`

writeFileSync(OUT, css)
console.log(`Wrote ${OUT}`)

// The same values for script: sizes (px at the default text size), durations (ms) and the JS springs.
const camel = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase())
const entries = (list, key, val) => list.map((t) => `  ${key(t.name)}: ${val(t.value)},`).join('\n')
const ts = `// Generated by scripts/gen-tokens.mjs from design/tokens.json — do not edit by hand.
// CSS reads the same tokens as custom properties (tokens.css); use these only where script needs the number.

/** Root font size at the default text size: tokens are authored in px at this size. */
export const BASE_PX = ${BASE_PX}
/** How far a size grows with Dynamic Type at most (CSS caps size tokens the same way). */
export const SIZE_MAX_SCALE = ${sizeMaxScale}

/** Spacing tokens in px at the default text size (space4 = space-4). */
export const SPACE = {
${entries(tokens.spacing.tokens, camel, px)}
} as const

/** Size tokens in px at the default text size (they grow with Dynamic Type: see scaled()). */
export const SIZE = {
${entries(tokens.size.tokens, camel, px)}
} as const

/** Duration tokens in ms. */
export const DURATION = {
${entries(tokens.duration.tokens, (n) => camel(n.replace(/^dur-/, '')), ms)}
} as const

/** JS springs (animateSpring in lib/spring.ts): Apple response (s) and damping ratio, matching the easing tokens. */
export const SPRING = {
${entries(tokens.spring.tokens, (n) => camel(n.replace(/^spring-/, '')), (v) => `{ response: ${v.response}, damping: ${v.damping} }`)}
} as const

/** A size authored in px at the default text size, as CSS that grows with Dynamic Type like a size token. */
export function cssSize(px: number): string {
  return \`min(\${+(px / BASE_PX).toFixed(4)}rem, \${+(px * SIZE_MAX_SCALE).toFixed(4)}px)\`
}

/** A size authored in px at the default text size, in px at the current text size (capped like a size token). */
export function scaled(px: number): number {
  const root = parseFloat(getComputedStyle(document.documentElement).fontSize) || BASE_PX
  return Math.min((px / BASE_PX) * root, px * SIZE_MAX_SCALE)
}
`
const OUT_TS = resolve(root, 'src/styles/tokens.ts')
writeFileSync(OUT_TS, ts)
console.log(`Wrote ${OUT_TS}`)
